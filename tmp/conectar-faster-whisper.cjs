const fs = require('fs');
const serverFile = 'D:/xampp/htdocs/wsp/server.js';
const htmlFile = 'D:/xampp/htdocs/wsp/index.html';
let server = fs.readFileSync(serverFile, 'utf8');
let html = fs.readFileSync(htmlFile, 'utf8');
const previous = "const WHISPER_SCRIPT_PATH = path.join(WHISPER_PROJECT_ROOT, 'run_script.bat');";
if (!server.includes(previous) || !html.includes('Ejecutar run_script.bat')) throw new Error('La estructura del módulo cambió; no se modificaron archivos.');
const backups = 'tmp/whatsapp-diario/';
if (!fs.existsSync(backups + 'server-antes-faster-whisper.js')) fs.writeFileSync(backups + 'server-antes-faster-whisper.js', server);
if (!fs.existsSync(backups + 'index-antes-faster-whisper.html')) fs.writeFileSync(backups + 'index-antes-faster-whisper.html', html);
server = server.replace(previous, "const WHISPER_SCRIPT_PATH = 'C:/Users/Andres/Documents/Codex/2026-11-01/ex/outputs/Probar-faster-whisper.cmd';");
server = server.replace('createWhisperWorkflow({ projectRoot: WHISPER_PROJECT_ROOT, logPath:', 'createWhisperWorkflow({ projectRoot: WHISPER_PROJECT_ROOT, launcherPath: WHISPER_SCRIPT_PATH, logPath:');
server = server.replace('Whisper está preparando la transcripción.', 'Faster-whisper está ejecutando Probar-faster-whisper.cmd.');
server = server.replace('Whisper terminó correctamente.', 'Faster-whisper terminó correctamente.');
html = html.replaceAll('Ejecutar run_script.bat', 'Ejecutar Probar-faster-whisper.cmd');
html = html.replace('Whisper en proceso', 'Faster-whisper en proceso');
html = html.replace('Preparando Whisper y archivando las transcripciones anteriores...', 'Preparando faster-whisper y archivando las transcripciones anteriores...');
fs.writeFileSync(serverFile, server);
fs.writeFileSync(htmlFile, html);
console.log('Módulo conectado a Probar-faster-whisper.cmd; copias anteriores conservadas.');

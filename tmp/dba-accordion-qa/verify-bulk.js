async page => {
    const checks = [];
    const check = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
    const closedCount = scope => scope.locator('details[data-accordion-key]:not([open])').count();
    check(!await page.locator('#accordion-toolbar').isVisible(), 'Controles generales ocultos sin selección');
    await page.locator('#select-grado').selectOption('6');
    await page.locator('#select-materia').selectOption('1');
    const all = page.locator('#periods-container');
    const current = page.locator('.period-block[data-period="4"]');
    check(await page.locator('#accordion-toolbar').isVisible(), 'Controles generales disponibles al seleccionar');
    check(await page.locator('.period-block[open]').count() === 1, 'Se conserva la apertura inicial del vigente');
    await page.getByRole('button', {name:'Expandir todo del periodo 4',exact:true}).click();
    check(await closedCount(current) === 0, 'Un clic despliega todos los niveles del periodo');
    check(await page.locator('.period-block[open]').count() === 1, 'Expandir un periodo conserva cerrados los demás');
    const collapseCurrent = page.getByRole('button', {name:'Contraer todo del periodo 4',exact:true});
    await collapseCurrent.focus(); await page.keyboard.press('Enter');
    check(await current.getAttribute('open') !== null && await current.locator('details[open]').count() === 0, 'Contraer contenido mantiene disponibles los controles del periodo');
    await page.getByRole('button', {name:'Expandir todo de todos los periodos',exact:true}).click();
    check(await closedCount(all) === 0 && await page.locator('.period-block[open]').count() === 4, 'La expansión general abre los cuatro periodos y todos sus elementos');
    await page.evaluate(async () => { await dbaWorkspace.refresh(); });
    check(await closedCount(all) === 0, 'La expansión general se conserva al recargar datos');
    await page.getByRole('button', {name:'Contraer todo de todos los periodos',exact:true}).click();
    check(await all.locator('details[open]').count() === 0, 'La contracción general pliega todos los niveles');
    await page.evaluate(async () => { await dbaWorkspace.refresh(); });
    check(await all.locator('details[open]').count() === 0, 'La contracción manual se conserva al recargar');
    await page.locator('.period-block[data-period="1"] > summary').click();
    await page.getByRole('button', {name:'Expandir todo del periodo 1',exact:true}).click();
    check(await closedCount(page.locator('.period-block[data-period="1"]')) === 0, 'Los controles también funcionan en periodos no vigentes');
    await page.locator('#select-materia').selectOption('9');
    check(await page.locator('.period-block[open]').count() === 1 && await all.locator('.dba-card[open]').count() === 0, 'Otra materia conserva su estado independiente');
    await page.locator('#select-materia').selectOption('1');
    check(await closedCount(page.locator('.period-block[data-period="1"]')) === 0, 'Se recupera la expansión al volver a la materia');
    await page.setViewportSize({width:360,height:900});
    await page.getByRole('button', {name:'Expandir todo de todos los periodos',exact:true}).click();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Los controles y el contenido expandido caben en móvil');
    await page.getByRole('button', {name:'Contraer todo de todos los periodos',exact:true}).click();
    await page.locator('.period-block[data-period="4"] > summary').click();
    await page.screenshot({path:'D:/xampp/htdocs/guagua/output/playwright/dba-accordion/controles-movil.png',fullPage:true});
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'D:/xampp/htdocs/guagua/output/playwright/dba-accordion/controles-escritorio.png',fullPage:true});
    check((await page.evaluate(() => qaErrors)).length === 0, 'Sin errores JavaScript en los controles rápidos');
    return {pruebas:checks.length,resultados:checks};
}

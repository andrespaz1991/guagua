async (page) => {
    const checks = [];
    const check = (value, message) => { if (!value) throw new Error(message); checks.push(message); };
    await page.locator('#select-grado').selectOption('6');
    await page.locator('#select-materia').selectOption('1');
    const periods = page.locator('.period-block');
    const current = page.locator('.period-block[data-period="4"]');
    check(await periods.count() === 4, 'Se muestran los cuatro periodos');
    check(await page.locator('.period-block[open]').count() === 1 && await current.getAttribute('open') !== null, 'Solo el periodo vigente abre inicialmente');
    check(await page.locator('.estandar-card[open],.dba-card[open],.eje-item[open]').count() === 0, 'Los elementos comienzan plegados');
    await current.locator(':scope > summary').focus();
    await page.keyboard.press('Enter');
    check(await current.getAttribute('open') === null, 'El teclado cierra el periodo');
    await page.keyboard.press('Space');
    check(await current.getAttribute('open') !== null, 'El teclado abre el periodo');
    const standard = current.locator('.estandar-card').first();
    await standard.locator(':scope > summary').click();
    const dba = standard.locator('.dba-card').first();
    await dba.locator(':scope > summary').click();
    const groups = dba.locator('.curriculum-group');
    await groups.nth(0).locator(':scope > summary').click();
    const eje = groups.nth(0).locator('.eje-item').first();
    await eje.locator(':scope > summary').click();
    check(await eje.locator('.eje-body').isVisible(), 'Los ejes despliegan su descripción');
    await groups.nth(1).locator(':scope > summary').click();
    const evidence = groups.nth(1).locator('.ev-inline-item').first();
    await evidence.locator(':scope > summary').click();
    check(await evidence.locator('.evidence-body').isVisible(), 'Las evidencias despliegan su contenido');
    await evidence.locator('[data-ev-edit]').click();
    await page.locator('#ev-dialog[open]').waitFor();
    check(await current.getAttribute('open') !== null && await evidence.getAttribute('open') !== null, 'Editar evidencia conserva los acordeones abiertos');
    await page.locator('#ev-dialog-cancel').click();
    await dba.locator('.btn-edit-dba').click();
    await page.locator('#input-descripcion-dba').fill('Edición de interfaz en datos simulados.');
    await page.locator('#btn-save-dba').click();
    await page.waitForFunction(() => document.getElementById('modal-dba').classList.contains('hidden'));
    check(await standard.getAttribute('open') !== null && await dba.getAttribute('open') !== null && await eje.getAttribute('open') !== null && await evidence.getAttribute('open') !== null, 'Guardar y recargar conserva los elementos desplegados');
    const first = page.locator('.period-block[data-period="1"]');
    await first.locator(':scope > summary').click();
    await page.locator('#tab-evidencias').click();
    check(await page.locator('.ev-card').first().isVisible(), 'La biblioteca de evidencias sigue funcionando');
    await page.locator('#tab-editor').click();
    check(await first.getAttribute('open') !== null && await current.getAttribute('open') !== null, 'Cambiar de pestaña conserva la elección manual');
    await page.locator('#select-materia').selectOption('9');
    check(await page.locator('.period-block[open]').count() === 1, 'Una materia nueva abre solo el periodo vigente');
    await page.locator('#select-materia').selectOption('1');
    check(await page.locator('.period-block[open]').count() === 2, 'Volver a una materia recupera sus acordeones');
    await page.evaluate(async () => { qaData.periodo_actual = 2; await dbaWorkspace.refresh(); });
    check(await page.locator('.period-block[open]').count() === 1 && await page.locator('.period-block[data-period="2"]').getAttribute('open') !== null, 'Un cambio de periodo configurado abre el nuevo vigente');
    await page.evaluate(async () => { qaData.periodo_actual = null; await dbaWorkspace.refresh(); });
    check(await page.locator('.period-block[open]').count() === 0, 'Sin periodo vigente todos inician cerrados');
    check((await page.locator('#view-subtitle').textContent()).includes('No hay un periodo vigente'), 'La ausencia de periodo se explica en pantalla');
    await page.reload();
    await page.locator('#select-grado').selectOption('6');
    await page.locator('#select-materia').selectOption('1');
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'D:/xampp/htdocs/guagua/output/playwright/dba-accordion/escritorio.png',fullPage:true});
    await page.setViewportSize({width:360,height:800});
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'La vista móvil cerrada no tiene desbordamiento horizontal');
    await current.locator('.estandar-card > summary').first().click();
    await current.locator('.dba-card > summary').first().click();
    await current.locator('.curriculum-group > summary').first().click();
    await current.locator('.eje-item > summary').first().click();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'La jerarquía expandida cabe en 360 píxeles');
    await page.screenshot({path:'D:/xampp/htdocs/guagua/output/playwright/dba-accordion/movil.png',fullPage:true});
    await page.locator('#theme-toggle').click();
    check(await page.locator('html').getAttribute('data-theme') === 'dark', 'Los acordeones conservan el tema oscuro');
    await page.locator('#theme-toggle').click();
    await page.locator('#tab-exportar').click();
    await page.locator('#export-use-editor').click();
    check((await page.locator('#export-summary').textContent()).includes('DBA'), 'La exportación sigue recibiendo los datos');
    check((await page.evaluate(() => qaErrors)).length === 0, 'Sin errores JavaScript durante los flujos');
    return {pruebas:checks.length,resultados:checks};
}

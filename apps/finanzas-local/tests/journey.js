async (page) => {
  const output = 'D:/xampp/htdocs/guagua/output/playwright/horizonte';
  const fixtures = 'D:/xampp/htdocs/guagua/apps/finanzas-local/tests/fixtures';
  const checks = [];
  const errors = [];
  page.setDefaultTimeout(15000);
  page.removeAllListeners('dialog');
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept().catch(() => {}));
  const assert = (ok, name) => { if (!ok) throw new Error(name); checks.push(name); };
  const nav = name => page.getByRole('navigation').getByRole('button', {name, exact:false}).click();
  const state = () => page.evaluate(() => Horizonte.getState());
  await page.evaluate(() => {try {dirty=false;} catch {}});
  await page.goto('http://127.0.0.1:8765');
  await page.waitForSelector('#cashChart');
  assert(await page.locator('#month option').count() === 12, 'Se muestran 12 meses consecutivos');
  assert(await page.evaluate(() => Chart.getChart('cashChart').data.datasets.length) === 3, 'Chart.js muestra ingresos, gastos y ahorro');
  await page.screenshot({path:output+'/01-panel.png',fullPage:true});
  await nav('Documentos y análisis');
  await page.locator('#pdfFiles').setInputFiles(fixtures+'/no-es-pdf.pdf');
  await page.locator('#upload').click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('Solo se admiten'));
  assert((await state()).months[0].ledger.length === 0, 'Un archivo falso no actualiza las finanzas');
  await page.locator('#pdfFiles').setInputFiles(fixtures+'/extracto-demo.pdf');
  await page.locator('#upload').click();
  await page.waitForSelector('#documentList [data-analyze]');
  assert((await state()).months[0].ledger.length === 0, 'Subir un PDF no aplica datos sin revisión');
  await page.locator('#documentList [data-analyze]').first().click();
  await page.waitForSelector('#review[open]');
  assert(await page.locator('#reviewRows tr').count() === 6, 'El analizador extrae los seis movimientos');
  assert(await page.locator('#reviewOpening').inputValue() === '1000000', 'Extrae saldo inicial de un millón');
  assert(await page.locator('#reviewClosing').inputValue() === '3350000', 'Extrae el saldo final');
  assert(await page.locator('#applyReview').isDisabled(), 'La aplicación requiere confirmación explícita');
  await page.locator('#verified').check();
  await page.locator('#applyReview').click();
  assert((await state()).months[0].ledger.length === 0, 'No permite aplicar movimientos sin clasificar');
  await page.locator('#reviewRows tr').nth(4).locator('[data-k=kind]').selectOption('transferOut');
  await page.locator('#reviewRows tr').nth(5).locator('[data-k=kind]').selectOption('inversion');
  await page.locator('#verified').check();
  await page.locator('#reviewRows tr').nth(1).locator('[data-k=amount]').fill('1700000');
  assert(!(await page.locator('#verified').isChecked()), 'Editar una fila invalida la confirmación anterior');
  await page.locator('#reviewClosing').fill('3450000');
  await page.locator('#verified').check();
  await page.screenshot({path:output+'/02-revision-pdf.png',fullPage:true});
  await page.locator('#applyReview').click();
  await page.waitForSelector('#reconcile:not([hidden])');
  let m = (await state()).months[0];
  assert(m.income.salario === 5500000 && m.expenses.vivienda === 1700000, 'Los totales usan los valores corregidos');
  assert(m.expenses.otros === 0 && m.investments.fija.contribution === 400000, 'Transferencias e inversión no se cuentan como gasto');
  assert(m.ledger.length === 6 && m.accounts[0].manualIn === 0 && m.accounts[0].manualOut === 0, 'El primer extracto reemplaza las entradas manuales de ejemplo');
  assert(m.passive === 0, 'El ingreso pasivo de ejemplo no sobrevive a un extracto solo salarial');
  await page.locator('[data-confirm-account]').click();
  assert((await state()).months[0].accounts[0].confirmed, 'Se concilia la cuenta sin diferencias');
  assert((await state()).months[0].assets[0].value === 3450000, 'La conciliación actualiza el activo bancario');
  await nav('Documentos y análisis');
  await page.locator('#pdfFiles').setInputFiles(fixtures+'/extracto-demo.pdf');
  await page.locator('#upload').click();
  await page.waitForFunction(() => !document.querySelector('#upload').disabled);
  assert(await page.locator('#documentList [data-analyze]').count() === 1, 'Repetir una subida no duplica documentos');
  assert(await page.locator('#documentList [data-analyze]').isDisabled(), 'Un documento aplicado no puede aplicarse dos veces');
  await page.locator('#pdfFiles').setInputFiles(fixtures+'/otro-extracto-demo.pdf');
  await page.locator('#upload').click();
  await page.waitForFunction(() => document.querySelectorAll('#documentList [data-analyze]').length === 2);
  await page.locator('#documentList [data-analyze]:not([disabled])').click();
  await page.waitForSelector('#review[open]');
  assert(await page.locator('#applyMode').inputValue() === 'add', 'El segundo documento propone sumar solo los movimientos nuevos');
  await page.locator('#reviewClosing').fill('3850000');
  await page.locator('#verified').check();
  await page.locator('#applyReview').click();
  m = (await state()).months[0];
  assert(m.income.freelance === 500000 && m.expenses.transporte === 100000 && m.ledger.length === 8, 'El segundo extracto se integra sin repetir el primero');
  assert(!m.accounts[0].confirmed, 'Un movimiento nuevo invalida la conciliación previa');
  await page.locator('[data-account] [data-k=closing]').fill('3800000');
  await page.locator('[data-confirm-account]').click();
  assert(!(await state()).months[0].accounts[0].confirmed, 'Una diferencia de saldo bloquea la conciliación');
  await page.locator('[data-account] [data-k=closing]').fill('3850000');
  await page.locator('[data-confirm-account]').click();
  await page.screenshot({path:output+'/03-conciliacion.png',fullPage:true});
  await nav('Cierre del mes');
  await page.locator('#closeMonth').click();
  assert((await state()).months[0].status === 'open', 'No se cierra sin verificar ejemplos y checklist');
  await nav('Registro mensual');
  await page.locator('#emergency').fill('1000000');
  await page.locator('#monthlyForm button[type=submit]').click();
  await nav('Balance general');
  await page.locator('#saveAssets').click();
  await page.locator('#saveDebts').click();
  await nav('Inversiones');
  await page.locator('#saveInvest').click();
  const math = await page.evaluate(() => {
    const s = Horizonte.getState(), ds=s.months[0].debts;
    const p=Horizonte.payoff(ds,300000,'avalanche'), b=Horizonte.payoff(ds,0,'avalanche');
    return {zero:Horizonte.future(1000,100,0,5),negative:Horizonte.future(1000,0,-10,1),p,b,impossible:Horizonte.payoff([{balance:1000,rate:100,min:1}],0,'avalanche').months, noDebt:Horizonte.payoff([],0,'avalanche').months,valid:!!Horizonte.validateState(s)};
  });
  assert(math.zero === 7000, 'La inversión a tasa cero usa capital más aportes');
  assert(Math.abs(math.negative-900)<0.01, 'El simulador admite escenarios de rendimiento negativo');
  assert(math.p.months < math.b.months && math.p.interest < math.b.interest, 'Un extra reduce plazo e intereses');
  assert(math.impossible === null && math.noDebt === 0 && math.valid, 'Controla deuda no amortizable, deuda cero y respaldo válido');
  await nav('Deudas y créditos');
  await page.locator('#strategy').selectOption('snowball');
  await page.locator('#simulateDebt').click();
  assert((await page.locator('#debtOrder').textContent()).includes('Tarjeta de crédito'), 'Bola de nieve presenta su prioridad');
  await page.locator('#loanRate').fill('0');
  await page.locator('#loanExtra').fill('0');
  await page.locator('#simulateLoan').click();
  assert((await page.locator('#loanResult').textContent()).includes('36 meses'), 'Crédito sin interés respeta el plazo original');
  await nav('Cierre del mes');
  await page.locator('#closeChecks input').evaluateAll(inputs => inputs.forEach(input => {input.click();}));
  await page.locator('#closeDecision').fill('Reservar 300.000 para reducir la tarjeta el próximo mes.');
  await page.locator('#closeMonth').click();
  m=(await state()).months[0];
  assert(m.status==='closed' && m.assessment.totals.income===6000000 && m.assessment.totals.expenses===2550000, 'El cierre genera una evaluación con los totales verificados');
  assert(m.assessment.totals.assets-m.assessment.totals.debts===67550000, 'El patrimonio del cierre refleja la cuenta conciliada');
  await page.screenshot({path:output+'/04-cierre.png',fullPage:true});
  await nav('Registro mensual');
  assert(await page.locator('#in-salario').isDisabled(), 'El cierre protege el registro mensual');
  await nav('Cierre del mes');
  await page.locator('#prepareFromClose').click();
  await page.locator('#confirmCopy').click();
  assert((await state()).selected==='2026-12', 'Desde un mes cerrado se prepara el siguiente presupuesto');
  await page.locator('#month').selectOption('2026-11');
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export').click();
  const download=await downloadPromise;
  await download.saveAs(output+'/respaldo-e2e.json');
  const before=await state();
  await page.locator('#jsonFile').setInputFiles({name:'invalido.json',mimeType:'application/json',buffer:Buffer.from('{"schema":1,"months":[]}')});
  assert((await state()).months[0].status==='closed', 'Un JSON inválido conserva la sesión actual');
  await page.locator('#jsonFile').setInputFiles(output+'/respaldo-e2e.json');
  await page.waitForSelector('#importDialog[open]');
  await page.locator('#confirmImport').click();
  assert(JSON.stringify(before)===JSON.stringify(await state()), 'Exportar e importar preserva todos los datos y el assessment');
  await nav('Cierre del mes');
  await page.locator('#reopen').click();
  assert((await state()).months[0].status==='open' && (await state()).months[0].assessment===null, 'Reabrir invalida la evaluación anterior');
  await nav('Vista general');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth+1), 'La vista móvil no desborda horizontalmente');
  await page.screenshot({path:output+'/05-movil.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  assert(errors.length===0, 'No hay errores JavaScript durante el recorrido');
  await page.evaluate(result => {window.__journeyResult=result;}, {passed:checks.length,checks,errors});
  return {passed:checks.length,checks,errors};
}

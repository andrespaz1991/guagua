const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const { JSDOM } = createRequire(path.resolve(process.argv[2] || '.', 'package.json'))('jsdom');
const data = require('./dba_export_test.cjs');
const root = path.resolve(__dirname, '../apps/dba');
let html = fs.readFileSync(path.join(root, 'index.php'), 'utf8');
html = html.replace("<?php require __DIR__ . '/views/evidencias.php'; ?>", fs.readFileSync(path.join(root, 'views/evidencias.php'), 'utf8'));
html = html.replace(/<\?php[\s\S]*?\?>/g, '').replace(/<script[^>]*src[^>]*><\/script>/g, '');
const dom = new JSDOM(html, { url: 'http://localhost/guagua/apps/dba/', runScripts: 'outside-only' });
const w = dom.window, $ = id => w.document.getElementById(id);
const downloads = [], blobs = [], errors = [];
let fail = false, reads = 0;
w.addEventListener('error', event => errors.push(event.error));
w.console.error = () => {};
w.fetch = async () => {
    reads++;
    return { ok: !fail, json: async () => fail ? { status: 'error', message: 'Sin conexión' } : { status: 'success', data } };
};
w.URL.createObjectURL = blob => { blobs.push(blob); return `blob:test-${blobs.length}`; };
w.URL.revokeObjectURL = () => {};
w.HTMLAnchorElement.prototype.click = function () { downloads.push(this.download); };
const tick = () => new Promise(resolve => setTimeout(resolve, 20));
const change = (id, value) => { $(id).value = value; $(id).dispatchEvent(new w.Event('change', { bubbles: true })); };
const readBlob = blob => new Promise(resolve => { const r = new w.FileReader(); r.onload = () => resolve(r.result); r.readAsText(blob); });
for (const file of ['app.js', 'evidencias.js', 'exportar.js']) w.eval(fs.readFileSync(path.join(root, 'assets/js', file), 'utf8'));
(async () => {
    assert.equal($('btn-exportar').disabled, true);
    await tick();
    $('tab-exportar').click();
    assert.equal($('exportar-view').classList.contains('hidden'), false);
    assert.equal($('editor-view').classList.contains('hidden'), true);
    assert.equal($('tab-exportar').getAttribute('aria-selected'), 'true');
    assert.equal($('export-grado').options.length, 3);
    change('select-grado', '6'); change('select-materia', '1');
    $('export-use-editor').click();
    assert.equal($('export-grado').value, '6');
    assert.equal($('export-materia').value, '1');
    change('export-periodo', '2');
    assert.match($('export-summary').textContent, /2 estándares · 2 DBA · 2 ejes temáticos · 2 evidencias/);
    for (const format of ['json', 'csv', 'txt']) {
        change('export-formato', format);
        const previous = reads;
        $('btn-exportar').click();
        assert.equal($('export-periodo').disabled, true);
        $('btn-exportar').click();
        await tick();
        assert.equal(reads, previous + 1, 'Una sola consulta nueva por descarga');
        assert.equal($('export-periodo').disabled, false);
        assert.match(downloads.at(-1), new RegExp(`malla_grado-6_materia-1_periodo-2_.*\\.${format}$`));
        assert.match($('export-result').textContent, /Descarga iniciada/);
    }
    assert.equal(downloads.length, 3);
    const json = JSON.parse(await readBlob(blobs[0]));
    assert.deepEqual(json.totales, { estandares: 2, dbas: 2, ejes_tematicos: 2, evidencias: 2 });
    assert.match(await readBlob(blobs[1]), /tipo_registro/);
    assert.match(await readBlob(blobs[2]), /MALLA CURRICULAR/);
    change('export-periodo', '4');
    assert.equal($('btn-exportar').disabled, true);
    assert.match($('export-summary').textContent, /No hay registros/);
    change('export-periodo', '2'); fail = true;
    $('btn-exportar').click(); await tick();
    assert.equal(downloads.length, 3, 'No descargar datos antiguos si falla la actualización');
    assert.match($('export-result').textContent, /No se pudieron actualizar/);
    assert.equal($('btn-exportar').disabled, false, 'Permite reintentar');
    fail = false;
    data.estandares = data.estandares.filter(e => e.id_estandar !== '14');
    $('btn-exportar').click(); await tick();
    assert.match($('export-summary').textContent, /1 estándares/);
    assert.equal(downloads.length, 4);
    $('tab-editor').click();
    assert.equal($('exportar-view').classList.contains('hidden'), true);
    $('tab-editor').dispatchEvent(new w.KeyboardEvent('keydown', { key: 'End', bubbles: true }));
    assert.equal($('exportar-view').classList.contains('hidden'), false, 'Acceso por teclado');
    assert.equal(errors.length, 0, errors.map(String).join('\n'));
    console.log('OK: pestaña, selectores, resumen, tres descargas, actualización de datos, bloqueo de duplicados, filtros vacíos, fallo de red y teclado.');
    dom.window.close();
})().catch(error => { console.error(error); dom.window.close(); process.exitCode = 1; });

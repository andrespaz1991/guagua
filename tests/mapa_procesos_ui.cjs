async (page) => {
  const checks=[];
  const ok=(condition,message)=>{if(!condition)throw new Error(message);checks.push(message);};
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const clickNode=async id=>{
    await page.locator(`[data-node="${id}"]`).click();
    await page.waitForFunction(id=>{
      const node=[...document.querySelectorAll('#gm-nodes [data-node]')].find(n=>n.dataset.node===id);
      return node?.getAttribute('aria-pressed')==='true'&&node.getAttribute('aria-expanded')!=='false';
    },id);
  };
  const doubleClickWindow=async id=>{
    const opened=page.context().waitForEvent('page');
    await page.locator(`[data-node="${id}"]`).dblclick();
    const popup=await opened;
    await popup.waitForLoadState('domcontentloaded');
    return popup;
  };
  await page.context().route('http://localhost/guagua/**',route=>route.fulfill({status:200,contentType:'text/html',body:'<!doctype html><title>Pantalla de prueba</title><p>Módulo de prueba</p>'}));
  await page.setViewportSize({width:1440,height:1080});
  await page.goto('http://127.0.0.1:8764/');
  await page.locator('[data-node="apertura"]').waitFor();
  ok(await page.locator('[data-node]').count()===8,'Vista general con siete ramas');
  const initial=await page.locator('[data-node]').evaluateAll(nodes=>nodes.map(n=>n.dataset.node));
  const branchWindow=await doubleClickWindow('apertura');
  await branchWindow.locator('[data-node="periodos"]').waitFor();
  ok(await branchWindow.locator('[data-node]').count()===15,'El doble clic en una rama abre su mapa en otra ventana');
  await branchWindow.close();
  await page.waitForTimeout(550);
  ok(await page.locator('[data-node]').count()===8,'El doble clic no ejecuta también la expansión del clic sencillo');
  await clickNode('apertura');
  ok(await page.locator('[data-node="periodos"]').count()===1,'La rama de apertura despliega períodos');
  ok(await page.locator('[data-node]').count()===15,'Desplegar una rama añade sus procesos al árbol completo');
  ok(await page.locator('[data-node]').evaluateAll((nodes,ids)=>ids.every(id=>nodes.some(n=>n.dataset.node===id)),initial),'Se conservan Guagua y las siete ramas anteriores');
  await clickNode('periodos');
  ok(await page.locator('#gm-detail h2').textContent()==='Configurar períodos','El proceso seleccionado actualiza el detalle');
  ok((await page.locator('#gm-detail').textContent()).includes('F03'),'El detalle conserva evidencia del diagnóstico');
  ok((await page.locator('#gm-detail a').first().getAttribute('href')).endsWith('/guagua/Planeador/periodo.php'),'Enlace a la pantalla real del período');
  ok(await page.locator('[data-node="modulo:periodos:0"]').count()===1,'Un proceso despliega los módulos como hijos');
  const beforeWindow=page.url();
  const moduleWindow=await doubleClickWindow('modulo:periodos:0');
  ok(moduleWindow.url()==='http://localhost/guagua/Planeador/periodo.php','El doble clic en un módulo abre su pantalla en otra ventana');
  ok(await moduleWindow.evaluate(()=>window.opener===null),'La ventana nueva no tiene acceso al mapa de origen');
  await moduleWindow.close();
  await page.waitForTimeout(550);
  ok(page.url()===beforeWindow,'Abrir una ventana conserva la selección y las ramas del mapa original');
  const processWindow=await doubleClickWindow('periodos');
  ok(processWindow.url()==='http://localhost/guagua/Planeador/periodo.php','El doble clic en un proceso abre su pantalla principal');
  await processWindow.close();
  await page.locator('[data-node="modulo:periodos:0"]').focus();
  const keyboardOpened=page.context().waitForEvent('page');
  await page.keyboard.press('Shift+Enter');
  const keyboardWindow=await keyboardOpened;
  await keyboardWindow.waitForLoadState('domcontentloaded');
  ok(keyboardWindow.url()==='http://localhost/guagua/Planeador/periodo.php','Mayús y Entrar abren el módulo con teclado');
  await keyboardWindow.close();
  await clickNode('modulo:periodos:0');
  ok(await page.locator('#gm-breadcrumb button').allTextContents().then(parts=>parts.join(' / '))==='Guagua / Apertura del año / Configurar períodos / Períodos académicos','Las migas muestran la ruta completa hasta el módulo');
  ok(await page.locator('#gm-detail h2').textContent()==='Períodos académicos','El módulo seleccionado tiene su propio detalle');
  await page.screenshot({path:'output/playwright/guagua-expansion-y-migas.png',fullPage:true});
  const expandedCount=await page.locator('[data-node]').count();
  await page.locator('#gm-breadcrumb [data-select="periodos"]').click();
  ok(await page.locator('[data-node]').count()===expandedCount,'Volver al proceso desde las migas conserva sus hijos');
  await page.locator('#gm-breadcrumb [data-overview]').click();
  ok(await page.locator('[data-node]').count()===expandedCount,'La miga Guagua conserva todo lo desplegado');
  await page.locator('#gm-fit').click();
  await clickNode('familias');
  ok(await page.locator('[data-node="modulo:periodos:0"]').count()===1,'Abrir otra rama conserva la expansión anterior');
  ok(await page.locator('[data-node="acudientes"]').count()===1,'Varias ramas pueden permanecer abiertas');
  await page.locator('#gm-fit').click();
  await page.locator('[data-toggle="apertura"]').click();
  ok(await page.locator('[data-node="periodos"]').count()===0 && await page.locator('[data-node="acudientes"]').count()===1,'Contraer una rama solo oculta sus descendientes');
  await clickNode('apertura');
  ok(await page.locator('[data-node="modulo:periodos:0"]').count()===1,'Reabrir una rama recupera la expansión de sus procesos');
  await clickNode('horario');
  await page.locator('#gm-zoom-in').click();
  const zoom=await page.locator('#gm-world').getAttribute('style');
  await clickNode('periodos');
  ok(await page.locator('#gm-world').getAttribute('style')===zoom,'Seleccionar otro proceso de la rama conserva zoom y posición');
  await clickNode('horario');
  await page.locator('#gm-detail [data-select="excel_asistencia"]').click();
  ok(await page.locator('#gm-detail h2').textContent()==='Sincronizar planilla','Una dependencia permite saltar a otra rama');
  await page.locator('[data-mode="propuesto"]').click();
  ok(await page.locator('[data-node]').count()===11,'El flujo recomendado contiene las etapas completas');
  const missingWindow=await doubleClickWindow('cierre_periodo');
  await missingWindow.locator('#gm-detail h2').waitFor();
  ok(await missingWindow.locator('#gm-detail h2').textContent()==='Cerrar y reabrir período','Un proceso sin pantalla abre su detalle en una ventana del mapa');
  await missingWindow.close();
  await clickNode('cierre_periodo');
  ok((await page.locator('#gm-detail').textContent()).includes('No hay una pantalla integral'),'Una brecha no inventa un módulo implementado');
  await page.screenshot({path:'output/playwright/guagua-flujo-recomendado.png',fullPage:true});
  await page.locator('[data-mode="modulos"]').click();
  ok(await page.locator('.gm-directory-row').count()===61,'El directorio conserva las 61 entradas del respaldo');
  ok(await page.locator('.gm-directory-row').filter({hasText:'Acción de sesión'}).locator('a').count()===0,'Cerrar sesión no es una acción ejecutable del directorio');
  await page.locator('#gm-search').fill('matrimonio');
  ok(await page.locator('.gm-directory-row').count()===1,'La búsqueda filtra el directorio');
  await page.locator('.gm-directory-row [data-select]').click();
  ok(await page.locator('#gm-detail h2').textContent()==='Familias y acudientes','El directorio conecta con su proceso');
  await page.locator('[data-filter="gap"]').click();
  ok(await page.locator('[data-node="acudientes"]').count()===1 && await page.locator('[data-node="asistente"]').count()===0,'El filtro de brechas conserva solo los procesos correspondientes');
  const filteredCount=await page.locator('[data-node]').count();
  await page.locator('[data-overview]').click();
  ok(await page.locator('[data-node]').count()===filteredCount,'La miga de inicio conserva el filtro y las ramas desplegadas');
  await page.locator('[data-filter="core"]').click();
  await page.locator('#gm-fit').click();
  await clickNode('plataforma');
  await page.locator('[data-filter="optional"]').click();
  ok(await page.locator('[data-node="institucion"]').count()===0,'El filtro oculta procesos de otra condición');
  await page.locator('[data-filter="all"]').click();
  ok(await page.locator('[data-node="institucion"]').count()===1,'Mostrar todos recupera el árbol desplegado');
  await page.locator('#gm-search').fill('períodos');
  await page.locator('[data-search-select="periodos"]').click();
  await page.reload();
  await page.locator('[data-node="periodos"]').waitFor();
  ok(await page.locator('#gm-detail h2').textContent()==='Configurar períodos','Recargar conserva el enlace profundo al proceso');
  ok(await page.locator('[data-node="modulo:periodos:0"]').count()===1 && await page.locator('[data-node="institucion"]').count()===1,'Recargar restaura las ramas y procesos abiertos');
  await page.locator('#gm-sources').click();
  ok(await page.locator('#gm-source-dialog').isVisible(),'Las fuentes y el alcance están disponibles');
  await page.keyboard.press('Escape');
  ok(!(await page.locator('#gm-source-dialog').isVisible()),'El diálogo se cierra con teclado');
  await page.locator('[data-overview]').click();
  await page.screenshot({path:'output/playwright/guagua-mapa-general.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(180);
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'La vista móvil no desborda horizontalmente');
  const sizes=await page.locator('.gm-node-name').evaluateAll(nodes=>nodes.map(n=>({height:n.getBoundingClientRect().height,scale:n.getBoundingClientRect().width/n.offsetWidth,font:parseFloat(getComputedStyle(n).fontSize)})));
  ok(sizes.every(s=>s.font*s.scale>=13),'Los nodos mantienen texto legible en móvil');
  await clickNode('familias');
  await clickNode('acudientes');
  ok(await page.locator('#gm-detail h2').textContent()==='Familias y acudientes','Seleccionar un proceso también funciona en móvil');
  ok(await page.locator('[data-node="root"]').count()===1 && await page.locator('[data-node="modulo:acudientes:0"]').count()===1,'La expansión móvil también conserva los antecesores y añade módulos');
  await page.screenshot({path:'output/playwright/guagua-mapa-movil.png',fullPage:true});
  await page.locator('[data-mode="propuesto"]').click();
  await page.waitForTimeout(100);
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'El flujo recomendado se adapta al ancho móvil');
  await page.screenshot({path:'output/playwright/guagua-flujo-movil.png',fullPage:true});
  await page.setViewportSize({width:320,height:740});
  await page.waitForTimeout(180);
  ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'El diseño funciona también en 320 píxeles');
  ok(errors.length===0,'No se produjeron errores de JavaScript');
  await page.setViewportSize({width:1440,height:1080});
  await page.locator('[data-mode="actual"]').click();
  await page.goto('http://127.0.0.1:8764/#vista=actual&rama=constructor&proceso=toString');
  await page.locator('[data-node="root"]').waitFor();
  ok(await page.locator('[data-node]').count()===8,'Un enlace con identificadores no válidos vuelve al mapa general');
  return {checks:checks.length,results:checks,errors};
}

const assert = require('node:assert/strict');
const {calculate,annualRisk,resolveP4,degree,missingNotes,studentReport} = require('../apps/simulador_notas/model.js');
const row={p1:2.5,p2:3.3,p3:3.9};
const equal=[25,25,25,25];
let c=calculate(row,3,equal,3);
assert.ok(Math.abs(c.final-3.175)<1e-10);
assert.ok(Math.abs(c.required-2.3)<1e-10);
assert.equal(c.status,'pass');
assert.equal(calculate(row,2,equal,3).status,'risk');
assert.equal(calculate(row,null,equal,3).final,null);
assert.equal(calculate({...row,p2:null},5,equal,3).final,null);
assert.equal(calculate({...row,p2:null},5,[30,0,30,40],3).final,3.92);
assert.equal(calculate({p1:1,p2:1,p3:1},5,equal,3).required,9);
assert.equal(calculate({p1:5,p2:5,p3:5},1,equal,3).required,-3);
assert.equal(calculate({p1:3,p2:3,p3:3},3,equal,3).status,'pass');
assert.equal(calculate(row,3,[20,20,20,20],3).valid,false);
assert.equal(calculate(row,3,[30,30,40,0],3).valid,false);
assert.equal(calculate(row,3,[NaN,25,25,25],3).valid,false);
assert.equal(calculate(row,3,equal,6).valid,false);
assert.equal(calculate(row,0,equal,3).final,null);
assert.equal(calculate(row,5.1,equal,3).final,null);
assert.equal(calculate(row,2.299,equal,3).status,'risk');
assert.equal(calculate(row,2.3,equal,3).status,'pass');
c=calculate(row,4,[20,20,30,30],3);
assert.ok(Math.abs(c.final-3.53)<1e-10);
console.log('OK: promedios, meta exacta, pesos, notas ausentes, escala y nota necesaria.');

let risk=annualRisk({p1:2.5,p2:2.8,p3:2.8},null,equal,3);
assert.equal(risk.status,'risk');
assert.equal(risk.basis,'history');
assert.ok(Math.abs(risk.grade-2.7)<1e-10);
assert.ok(Math.abs(risk.accumulated-2.025)<1e-10);
assert.ok(Math.abs(risk.required-3.9)<1e-10);
assert.ok(Math.abs(risk.gap-0.3)<1e-10);
// Un acumulado inferior a 3 no implica que el promedio esté perdido.
assert.equal(annualRisk({p1:3.5,p2:3.5,p3:3.5},null,equal,3).status,'pass');
assert.equal(annualRisk({p1:3,p2:3,p3:3},null,equal,3).status,'pass');
// La final con P4 reemplaza al promedio histórico al evaluar el escenario.
assert.equal(annualRisk({p1:2.5,p2:2.8,p3:2.8},4,equal,3).status,'pass');
risk=annualRisk({p1:4,p2:3,p3:3},1,equal,3);
assert.equal(risk.status,'risk');
assert.equal(risk.basis,'final');
assert.equal(risk.grade,2.75);
assert.equal(risk.gap,0.25);
assert.equal(annualRisk({p1:1,p2:1,p3:1},null,equal,3).required,9);
risk=annualRisk({p1:2,p2:null,p3:2},null,equal,3);
assert.equal(risk.status,'incomplete');
assert.equal(risk.grade,null);
assert.equal(risk.accumulated,null);
assert.deepEqual(risk.missingPeriods,[2]);
risk=annualRisk({p1:2,p2:null,p3:2},null,[30,0,30,40],3);
assert.equal(risk.status,'risk');
assert.equal(risk.grade,2);
risk=annualRisk({p1:2,p2:3,p3:4},null,[10,20,30,40],3);
assert.equal(risk.status,'pass');
assert.ok(Math.abs(risk.historyAverage-10/3)<1e-10);
assert.equal(annualRisk({p1:null,p2:null,p3:null},null,[0,0,0,100],3).status,'incomplete');
assert.equal(annualRisk({p1:null,p2:null,p3:null},4,[0,0,0,100],3).status,'pass');
assert.equal(annualRisk(row,null,[20,20,20,20],3).status,'incomplete');
assert.equal(annualRisk(row,6,equal,3).status,'incomplete');
console.log('OK: alertas anuales, acumulado, promedio ponderado, recuperación con P4 y notas incompletas.');
const updatedUrbanity={p1:1.8,p2:2.5,p3:3.4};
assert.equal(annualRisk(updatedUrbanity,4.1,equal,3).status,'risk');
assert.equal(annualRisk(updatedUrbanity,4.5,equal,3).status,'pass');
assert.ok(Math.abs(annualRisk(updatedUrbanity,4.5,equal,3).final-3.05)<1e-10);
// La base es el PDF; las simulaciones permiten sobrescribir, vaciar y restaurar P4.
const pdfRow={id:'pdf-row',year:'2026',group:'02 Completa 8 8 2026',student:'Estudiante de prueba',code:'DEMO',subject:'Matemáticas',p1:2.5,p2:3.3,p3:3.9,p4:3.1,source_page:1};
assert.equal(resolveP4(pdfRow,{}),3.1);
assert.equal(resolveP4(pdfRow,{'pdf-row':4.5}),4.5);
assert.equal(resolveP4(pdfRow,{'pdf-row':null}),null);
assert.equal(resolveP4(pdfRow,{'pdf-row':6}),null);
assert.equal(resolveP4({...pdfRow,p4:null},{}),null);
assert.equal(resolveP4({...pdfRow,p4:null},{'pdf-row':4}),4);
assert.equal(pdfRow.p4,3.1);
assert.ok(Math.abs(calculate(pdfRow,resolveP4(pdfRow,{}),equal,3).final-3.2)<1e-10);
assert.ok(Math.abs(calculate(pdfRow,resolveP4(pdfRow,{'pdf-row':4.5}),equal,3).final-3.55)<1e-10);
console.log('OK: base PDF, P4 editable, restauración, vacíos y cálculo sin modificar el documento.');
const source={source:'Reporte de prueba.pdf'};
assert.equal(missingNotes([pdfRow],source).length,0);
const pendingRow={...pdfRow,p1:null,p4:null};
let missing=missingNotes([pendingRow],source);
assert.deepEqual(missing.map(entry=>entry.period),[1,4]);
assert.ok(missing.every(entry=>entry.status==='missing'&&entry.source===source.source&&entry.page===1));
assert.equal(missingNotes([{...pdfRow,p2:0}],source)[0].status,'invalid');
// Completar una simulación no oculta el vacío de la fuente.
assert.equal(resolveP4(pendingRow,{'pdf-row':4}),4);
assert.equal(missingNotes([pendingRow],source).length,2);
assert.equal(missingNotes([],source).length,0);
console.log('OK: faltantes de los cuatro periodos, página del PDF y separación de la simulación.');
const reportRows=[{p1:1.8,p2:2.5,p3:3.4,p4:4.5},{p1:4.6,p2:4.8,p3:4.1,p4:3.9}];
let report=studentReport(reportRows,equal,3);
assert.equal(report.complete,2);
assert.equal(report.pending,0);
assert.equal(report.risks,0);
assert.ok(Math.abs(report.subjects[1].result.final-4.35)<1e-10);
assert.ok(Math.abs(report.average-3.7)<1e-10);
report=studentReport([...reportRows,{p1:3,p2:null,p3:3,p4:3}],equal,3);
assert.equal(report.total,3);
assert.equal(report.complete,2);
assert.equal(report.pending,1);
assert.ok(Math.abs(report.average-3.7)<1e-10);
assert.equal(report.periods[1].count,2);
assert.ok(Math.abs(report.periods[1].average-3.65)<1e-10);
assert.equal(studentReport([{p1:1,p2:1,p3:1,p4:1}],equal,3).risks,1);
assert.equal(studentReport([{p1:3,p2:null,p3:3,p4:3}],[30,0,30,40],3).complete,1);
assert.equal(studentReport([{p1:3,p2:3,p3:3,p4:null}],equal,3).average,null);
assert.equal(studentReport([],equal,3).average,null);
assert.ok(studentReport([],equal,3).periods.every(period=>period.average===null&&period.count===0));
assert.ok(Math.abs(studentReport([reportRows[1]],[10,20,30,40],3).average-4.21)<1e-10);
console.log('OK: fichas anuales, promedio por materia, promedio general, pesos, periodos y resultados parciales sin convertir vacíos a cero.');
